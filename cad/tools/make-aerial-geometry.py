# ------------------------------------------------------- toroidal loop -------
def catmull_rom(pts, n=120, alpha=0.5):
    """CENTRIPETAL Catmull-Rom (alpha=0.5) through the control points, closed.

    Uniform Catmull-Rom (alpha=0) overshoots between widely spaced control
    points: the first version of this path dipped to r/R 0.1338 against a hub
    control point of 0.18, i.e. the loop passed INSIDE the hub boss it attaches
    to. Centripetal parameterisation is the standard remedy - it provably
    produces no cusps and no self-intersection within a segment (Yuksel et al.,
    "Parameterization and Applications of Catmull-Rom Curves", CAD 43(7), 2011).
    check-aerial-geometry.py asserts the result stays outboard of the hub.
    """
    def tj(ti, pi, pj):
        d = math.dist(pi, pj)
        return ti + d**alpha
    def seg(p0, p1, p2, p3, t):
        t0 = 0.0; t1 = tj(t0, p0, p1); t2 = tj(t1, p1, p2); t3 = tj(t2, p2, p3)
        if t1 == t0 or t2 == t1 or t3 == t2: return p1
        t = t1 + (t2 - t1) * t
        def lerp(a, b, ta, tb, tt):
            return tuple(((tb-tt)/(tb-ta))*x + ((tt-ta)/(tb-ta))*y for x, y in zip(a, b))
        A1 = lerp(p0, p1, t0, t1, t); A2 = lerp(p1, p2, t1, t2, t); A3 = lerp(p2, p3, t2, t3, t)
        B1 = lerp(A1, A2, t0, t2, t); B2 = lerp(A2, A3, t1, t3, t)
        return lerp(B1, B2, t1, t2, t)
    # OPEN path, root -> tip -> root. The loop is closed BY THE HUB, not by a spline
    # segment: the brief says each blade "leaves the hub, loops, and returns". Splining
    # the closing segment made the curve cut through the hub region, which is what drove
    # r/R down to 0.13. Endpoints are duplicated to give the end segments a tangent.
    P = [pts[0]] + list(pts) + [pts[-1]]
    segs = len(P) - 3; per = max(n // segs, 2); out = []
    for i in range(segs):
        for k in range(per):
            out.append(seg(P[i], P[i+1], P[i+2], P[i+3], k/per))
    out.append(tuple(pts[-1]))
    return out
