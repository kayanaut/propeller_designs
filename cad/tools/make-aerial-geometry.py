# ------------------------------------------------------- ducted fan duct -----
DF=dict(fan_D=90.0, Z=5, V=11, hub=0.45, tip_gap=0.4, lip_r=6.0, exit_area=0.85)
def duct(n=41):
    Rf=DF["fan_D"]/2; lip=DF["lip_r"]/Rf
    rows=[]
    for i in range(n):
        x=i/(n-1)
        if x<0.15:                                   # rounded inlet lip
            u=x/0.15; ri=1+lip*(1-math.sqrt(max(0.0,1-(1-u)**2)))
        elif x<0.45: ri=1.0                          # cylindrical across the rotor plane
        else:                                        # exit nozzle: area ratio 0.85
            u=(x-0.45)/0.55
            r_exit=math.sqrt(DF["exit_area"])
            ri=1.0+(r_exit-1.0)*(3*u*u-2*u**3)
        rows.append((x, ri, ri+naca4_thickness(max(x,1e-9), 0.10)))
    return rows
